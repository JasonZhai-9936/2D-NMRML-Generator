"""Write 2D NMR spectra as nmrML.

Layout (the "2D NMR Data in nmrML" file specification, as read by JSpectraViewer):
three uncompressed base64 little-endian Float64 arrays in <spectrumMultiD> (F2 axis,
F1 axis, row-major intensity grid) and optionally one <atomAssignment> with the
structure and the cross peaks as consecutive pairs of multiplets (F2 then F1).

The output is byte-identical to jsv2's build_2d_nmrml (JSpectraViewer), including
JavaScript's number formatting, so files from either tool are interchangeable.
"""
import base64
from decimal import Decimal

import numpy as np


def js_number(value):
    """Format a number the way JavaScript's String(number) does (ECMAScript Number::toString)."""
    if isinstance(value, (bool, np.bool_)):
        return 'true' if value else 'false'
    v = float(value)
    if v != v:
        return 'NaN'
    if v in (float('inf'), float('-inf')):
        return 'Infinity' if v > 0 else '-Infinity'
    if v == 0:
        return '0'
    if v < 0:
        return '-' + js_number(-v)
    # Shortest round-trip digits (Python repr and JavaScript agree on these)
    t = Decimal(repr(v)).as_tuple()
    all_digits = ''.join(map(str, t.digits))
    digits = all_digits.rstrip('0') or '0'
    exponent = t.exponent + len(all_digits) - len(digits)
    k = len(digits)
    n = k + exponent                     # value = 0.digits * 10^n
    if k <= n <= 21:
        return digits + '0' * (n - k)
    if 0 < n <= 21:
        return digits[:n] + '.' + digits[n:]
    if -6 < n <= 0:
        return '0.' + '0' * (-n) + digits
    e = n - 1
    exp = ('+' if e >= 0 else '-') + str(abs(e))
    return (digits if k == 1 else digits[0] + '.' + digits[1:]) + 'e' + exp


def encode_float64_base64(values):
    """Base64 of the values as little-endian 64-bit floats."""
    return base64.b64encode(np.ascontiguousarray(values, dtype='<f8').tobytes()).decode('ascii')


def escape_xml(text):
    return (str(text).replace('&', '&amp;').replace('<', '&lt;')
            .replace('>', '&gt;').replace('"', '&quot;'))


def _text(value):
    """Interpolate a value as JavaScript template literals do."""
    if isinstance(value, str):
        return value
    if isinstance(value, (int, float, np.integer, np.floating)):
        return js_number(value)
    return str(value)


def build_2d_nmrml(spectrum):
    """Build a 2D nmrML document.

    spectrum (dict):
      x, y        F2 and F1 axis values in ppm
      z           intensities, row-major with one row per y value (a 2D array of shape
                  (len(y), len(x)) or a flat array of len(x) * len(y) values)
      id          spectrum id (default "2D-spectrum")
      name        compound or spectrum name
      experiment  e.g. "1H-13C HSQC" (written as a comment)
      assignment  optional {atoms: [{id, element, x, y, z}], bonds: [{a1, a2, order}],
                  cross_peaks: [{x: {center, atom_refs}, y: {center, atom_refs}}]}
                  with atom_refs such as ["H13", "H14"] and ["C1"]
    Returns the nmrML text.
    """
    x = np.asarray(spectrum['x'], dtype=float).ravel()
    y = np.asarray(spectrum['y'], dtype=float).ravel()
    z = np.asarray(spectrum['z'], dtype=float).ravel()
    if z.size != x.size * y.size or x.size == 0 or y.size == 0:
        raise ValueError('2D nmrML: z length must equal x length * y length')
    sid = spectrum.get('id') or '2D-spectrum'
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<nmrML xmlns="http://nmrml.org/schema" version="1.0.rc1">',
             '  <!-- Generated by JSpectraViewer'
             + (': ' + escape_xml(spectrum['experiment']) if spectrum.get('experiment') else '') + ' -->',
             '  <spectrumList>',
             f'    <spectrumMultiD id="{escape_xml(sid)}" numberOfDataPoints="{z.size}">',
             f'      <spectrumDataArray2dIntensities compressed="false" byteFormat="Float64">{encode_float64_base64(z)}</spectrumDataArray2dIntensities>',
             f'      <spectrumDataArray2dDirectDimensionF2 compressed="false" byteFormat="Float64">{encode_float64_base64(x)}</spectrumDataArray2dDirectDimensionF2>',
             f'      <spectrumDataArray2dIndirectDimensionF1 compressed="false" byteFormat="Float64">{encode_float64_base64(y)}</spectrumDataArray2dIndirectDimensionF1>',
             '    </spectrumMultiD>',
             '  </spectrumList>']

    assignment = spectrum.get('assignment')
    if assignment and assignment.get('cross_peaks'):
        lines += ['  <spectrumAnnotationList>',
                  f'    <atomAssignment spectrumRef="{escape_xml(sid)}">',
                  '      <chemicalCompound>',
                  f'        <identifierList><identifier name="{escape_xml(spectrum.get("name") or "Compound")}"/></identifierList>']
        atoms = assignment.get('atoms') or []
        if atoms:
            lines += ['        <structure>', '          <atomList>']
            for a in atoms:
                lines.append(f'            <atom id="{escape_xml(_text(a["id"]))}" elementType="{escape_xml(_text(a["element"]))}" '
                             f'x="{_text(a["x"])}" y="{_text(a["y"])}" z="{_text(a["z"])}"/>')
            lines += ['          </atomList>', '          <bondList>']
            for b in assignment.get('bonds') or []:
                lines.append(f'            <bond atomRefs="{escape_xml(_text(b["a1"]))} {escape_xml(_text(b["a2"]))}" '
                             f'order="{_text(b.get("order") or 1)}"/>')
            lines += ['          </bondList>', '        </structure>']
        lines += ['      </chemicalCompound>', '      <atomAssignmentList>']
        for cp in assignment['cross_peaks']:
            for signal in (cp['x'], cp['y']):
                lines.append(f'        <multiplet center="{_text(signal["center"])}"><atoms atomRefs="'
                             f'{escape_xml(" ".join(signal["atom_refs"]))}"/></multiplet>')
        lines += ['      </atomAssignmentList>', '    </atomAssignment>', '  </spectrumAnnotationList>']
    lines.append('</nmrML>')
    return '\n'.join(lines) + '\n'
