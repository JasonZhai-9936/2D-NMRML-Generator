PEAKS = [(3.16, 28.9, 1.0), (7.67, 139.0, 0.6), (1.20, 20.0, 0.8)]   # (1H ppm, 13C ppm, height)


def write_pipe(path, noise=0.0):
    """A processed NMRPipe 1H-13C spectrum with Gaussian cross peaks at known shifts."""
    u = ng.fileiobase.create_blank_udic(2)
    for d, (label, obs, car, sw, n) in enumerate([('13C', 150.9, 80.0, 22000.0, 256), ('1H', 600.13, 4.7, 7200.0, 1024)]):
        u[d].update(label=label, obs=obs, car=car * obs, sw=sw, size=n, complex=False, time=False, freq=True)
    dic = ng.pipe.create_dic(u)
    data = np.zeros((256, 1024), 'float32')
    y = ng.pipe.make_uc(dic, data, 0).ppm_scale()
    x = ng.pipe.make_uc(dic, data, 1).ppm_scale()
    Y, X = np.meshgrid(y, x, indexing='ij')
    for h, c, a in PEAKS:
        data += (a * np.exp(-((X - h) / 0.02) ** 2 - ((Y - c) / 0.4) ** 2)).astype('float32')
    if noise:
        data += np.random.default_rng(0).normal(0, noise, data.shape).astype('float32')
    ng.pipe.write(path, dic, data, overwrite=True)
    return path


def strongest_near(s, h, c, dh=0.1, dc=3):
    x, y, z = s['x'], s['y'], np.abs(s['z'])
    rows, cols = np.abs(y - c) < dc, np.abs(x - h) < dh
    sub = z[np.ix_(rows, cols)]
    r, k = np.unravel_index(sub.argmax(), sub.shape)
    return y[rows][r], x[cols][k], sub.max() / z.max()


def test_nmrpipe_peaks_land_on_known_shifts(tmp_path):
    s = process_dataset(write_pipe(str(tmp_path / 'hsqc.ft2')))
    assert s['nuclei'] == ['1H', '13C'] and s['source'] == 'nmrpipe'
    for h, c, _ in PEAKS:
        cy, cx, rel = strongest_near(s, h, c)
        assert abs(cy - c) < 0.7 and abs(cx - h) < 0.02 and rel > 0.3


def test_clean_spectrum_untouched_by_noise_suppression(tmp_path):
    path = write_pipe(str(tmp_path / 'clean.ft2'))
    auto, off = process_dataset(path, noise='auto'), process_dataset(path, noise='off')
    assert np.array_equal(auto['z'], off['z'])
    assert not any(n.startswith('Noise suppressed') for n in auto['notes'])


def test_noisy_spectrum_cleaned_and_peaks_kept(tmp_path):
    path = write_pipe(str(tmp_path / 'noisy.ft2'), noise=0.08)
    s = process_dataset(path, noise='auto')
    assert any(n.startswith('Noise suppressed') for n in s['notes'])
    assert np.mean(s['z'] != 0) < 0.05                   # the noise floor is gone
    for h, c, _ in PEAKS:
        cy, cx, rel = strongest_near(s, h, c)
        assert abs(cy - c) < 1.5 and abs(cx - h) < 0.05 and rel > 0.2


def test_generate_from_dataset_result(tmp_path):
    result = generate_from_dataset(write_pipe(str(tmp_path / 'my hsqc.ft2')))
    assert result.file_name == 'my_hsqc_2D.nmrML'
    assert result.summary == '1024 x 256 points, 1H-13C HSQC'
    assert '<spectrumMultiD id="2D-my_hsqc"' in result.nmrml
    assert '<!-- Generated by JSpectraViewer: 1H-13C HSQC (nmrpipe) -->' in result.nmrml


def test_unrecognised_input(tmp_path):
    path = tmp_path / 'notes.txt'
    path.write_text('hello')
    with pytest.raises(InputError, match='Unrecognised file'):
        process_dataset(str(path))


@pytest.mark.network
def test_real_bruker_echo_antiecho_hsqc(real_file):
    """HMDB0000001 HSQC (raw Bruker ser, Echo-Antiecho). Without TopSpin referencing in the
    upload, the axes sit about 0.09 ppm (1H) and 1.8 ppm (13C) below HMDB's shifts."""
    s = process_dataset(real_file('hsqc'), magnitude=True)
    assert s['source'] == 'bruker-raw' and s['nuclei'] == ['1H', '13C']
    known = [(7.67, 139.0), (7.00, 121.6), (3.96, 56.8), (3.68, 33.5), (3.16, 28.9), (3.07, 28.9)]
    for h, c in known:
        cy, cx, rel = strongest_near(s, h - 0.09, c - 1.8, dh=0.035)   # the two CH2 peaks are 0.07 ppm apart
        assert abs(cy - (c - 1.8)) < 2.5 and abs(cx - (h - 0.09)) < 0.06 and rel > 0.15, (h, c)
