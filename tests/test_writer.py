import base64
import re

import numpy as np
import pytest

from nmr2d.nmrml_writer import build_2d_nmrml, js_number

# String(x) in JavaScript (Node.js), for the same values
JS_STRINGS = [
    (0, '0'), (-0.0, '0'), (1, '1'), (6.0, '6'), (-6, '-6'), (28.9, '28.9'), (3.065, '3.065'), (0.1, '0.1'),
    (0.5, '0.5'), (1e-7, '1e-7'), (1.5e-7, '1.5e-7'), (0.000001, '0.000001'), (0.0000012, '0.0000012'),
    (123456789012345680000.0, '123456789012345680000'), (1e21, '1e+21'), (1.234e21, '1.234e+21'),
    (-2.5e-10, '-2.5e-10'), (199.993896484375, '199.993896484375'), (0.00457763671875, '0.00457763671875'),
    (1 / 3, '0.3333333333333333'), (2 / 3 * 100, '66.66666666666666'), (5e-324, '5e-324'),
    (1.7976931348623157e308, '1.7976931348623157e+308'), (100, '100'), (1e20, '100000000000000000000'),
    (12345.678, '12345.678'),
]


@pytest.mark.parametrize('value,expected', JS_STRINGS)
def test_js_number_matches_javascript(value, expected):
    assert js_number(value) == expected


def decode(xml, tag):
    return np.frombuffer(base64.b64decode(re.search(f'<{tag}[^>]*>([^<]*)</{tag}>', xml).group(1)), '<f8')


def test_round_trip_arrays():
    x, y = np.linspace(10, 0, 7), np.linspace(150, 10, 5)
    z = np.random.default_rng(0).normal(size=(5, 7))
    xml = build_2d_nmrml({'x': x, 'y': y, 'z': z, 'name': 'Test', 'experiment': '1H-13C HSQC'})
    assert np.array_equal(decode(xml, 'spectrumDataArray2dDirectDimensionF2'), x)
    assert np.array_equal(decode(xml, 'spectrumDataArray2dIndirectDimensionF1'), y)
    assert np.array_equal(decode(xml, 'spectrumDataArray2dIntensities'), z.ravel())
    assert 'numberOfDataPoints="35"' in xml and '<!-- Generated by JSpectraViewer: 1H-13C HSQC -->' in xml
    assert '<atomAssignment' not in xml          # no assignment given


def test_assignment_block_and_escaping():
    xml = build_2d_nmrml({
        'x': [2, 1], 'y': [20, 10], 'z': [0, 1, 2, 3], 'id': 'a&b', 'name': 'A "quoted" <name>',
        'assignment': {'atoms': [{'id': '1', 'element': 'C', 'x': 0.5, 'y': 0, 'z': -1.25},
                                 {'id': '2', 'element': 'H', 'x': 1, 'y': 0, 'z': 0}],
                       'bonds': [{'a1': '1', 'a2': '2', 'order': 1}],
                       'cross_peaks': [{'x': {'center': 1.5, 'atom_refs': ['H2']}, 'y': {'center': 15.0, 'atom_refs': ['C1']}}]},
    })
    assert '<spectrumMultiD id="a&amp;b"' in xml and '<atomAssignment spectrumRef="a&amp;b">' in xml
    assert '<identifier name="A &quot;quoted&quot; &lt;name&gt;"/>' in xml
    assert '<atom id="1" elementType="C" x="0.5" y="0" z="-1.25"/>' in xml
    assert '<bond atomRefs="1 2" order="1"/>' in xml
    assert '<multiplet center="1.5"><atoms atomRefs="H2"/></multiplet>' in xml
    assert '<multiplet center="15"><atoms atomRefs="C1"/></multiplet>' in xml


def test_size_mismatch_rejected():
    with pytest.raises(ValueError):
        build_2d_nmrml({'x': [1, 2], 'y': [1], 'z': [1, 2, 3]})
